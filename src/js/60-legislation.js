  /* The stats bar under the Bills title: where the bills in view stand, one segment for each stage that has some (the stages of the Status menu, in its order), as wide
     as its share, and beside it each stage's count and its share of the bills in view as a percentage. It counts what the title counts, so it follows the jurisdiction chosen,
     the search and the filters; with no bills in view it is empty. Each percentage is rounded to a whole number on its own, so together they can come to a point or two either
     side of 100 (they are not forced to 100: that would change a figure to make the total look right). A share under 1% reads "<1%", and one over 99% when other stages have some
     reads ">99%", so a stage with bills never reads as none and a stage that is not all of them never reads as all; a screen reader is told "under 1%" and "over 99%". */
  function legStatsBar(list) {
    const stages = legGet.stages(), order = Object.keys(stages).filter(k => stages[k].active), by = {}, total = list.length;
    order.forEach(k => { by[k] = 0; });
    list.forEach(b => { if (b.stage in by) by[b.stage]++; });
    const parts = order.filter(k => by[k] > 0), name = k => String(stages[k].label).toLowerCase();
    if (!parts.length) return '';
    const share = (n, spoken) => { const p = 100 * n / total; return n === total ? '100%' : p < 1 ? (spoken ? 'under 1%' : '<1%') : p > 99 ? (spoken ? 'over 99%' : '>99%') : `${Math.round(p)}%`; };
    const say = parts.map(k => `${legNum(by[k])} ${name(k)} (${share(by[k], true)})`).join(', ');
    return `<span class="leg-stats-bar" role="img" aria-label="${escapeHTML(`Where the ${legNum(total)} ${total === 1 ? 'bill stands' : 'bills stand'}: ${say}.`)}">` +
      parts.map(k => `<span class="leg-stats-seg" data-stage="${escapeHTML(k)}" style="flex-grow:${by[k]}" title="${escapeHTML(`${stages[k].label}: ${legNum(by[k])} (${share(by[k])})`)}"></span>`).join('') + '</span>' +
      `<ul class="leg-stats-key">${parts.map(k => `<li><span class="leg-stats-swatch" data-stage="${escapeHTML(k)}"></span>${escapeHTML(`${legNum(by[k])} ${name(k)} (${share(by[k])})`)}</li>`).join('')}</ul>`;
  }

